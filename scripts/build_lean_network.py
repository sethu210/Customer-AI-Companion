r"""
Builds registries/customer_service/support_multi_agent_lean.hocon from support_multi_agent.hocon.

The lean variant is the same network without the Policy, Risk & Escalation agent: the orchestrator submits a
proposed action directly and lets the action layer's outcome (awaiting_confirmation, denied step_up_required,
queued ...) drive the conversation. That saves about two LLM calls per proposed action. Safety is unchanged:
submit_action runs the same deterministic checks either way; only the advisory dry run is skipped.

    .\.venv\Scripts\python.exe scripts\build_lean_network.py          # regenerate after editing the main network
tests/test_lean_network.py fails if the generated file is out of date.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "registries" / "customer_service" / "support_multi_agent.hocon"
TARGET = ROOT / "registries" / "customer_service" / "support_multi_agent_lean.hocon"

HEADER = ("# GENERATED by scripts/build_lean_network.py from support_multi_agent.hocon. Do not edit by hand:\n"
          "# edit the main network and re-run the script.\n"
          "# Lean variant: no Policy, Risk & Escalation agent; the orchestrator submits proposals directly.\n")

LEAN_STEP = """   - It proposed an action (issue status proposed with a proposal): call submit_action with that issue_id.
     The action layer checks everything (sign-in, the rules, limits, account review, confirmation) and its
     outcome is what you tell the customer:
       awaiting_confirmation -> explain exactly what will happen and ask the customer to confirm; submit again
                                with customer_confirmed=true only after they agree, in a later message.
       denied, reason step_up_required -> tell the customer account changes need a stronger sign-in (app,
                                website or verification link).
     Set customer_confirmed=true only if the customer clearly agreed to that exact action in an earlier
     message. Never ask a specialist to change a refusal into an approval.
"""


def replace_once(text: str, pattern: str, replacement: str, flags: int = 0) -> str:
    new, count = re.subn(pattern, lambda _m: replacement, text, count=0, flags=flags)
    if count != 1:
        raise SystemExit(f"expected exactly one match for {pattern[:70]!r}, found {count}; update the build script")
    return new


def build(source: str) -> str:
    text = replace_once(source, r"\A# Multi-agent customer support \(Phase 4[^\n]*\n", HEADER)
    text = replace_once(text, r"# policy_risk_escalation \(advice only; ", "# no policy agent (")
    text = replace_once(text, r'"description": "Multi-agent customer support: ',
                        '"description": "Multi-agent customer support (lean variant, no policy agent): ')
    text = replace_once(text, r"   - It proposed an action \(issue status proposed with a proposal\): first call "
                              r"policy_risk_escalation.*?change a refusal into an approval\.\n", LEAN_STEP, re.S)
    text = replace_once(text, r'"policy_risk_escalation", ', "")
    text = replace_once(text, r"        # -+ Policy, Risk & Escalation\n.*?(?=        # -+ coded tools: intake\n)", "",
                        re.S)
    text = replace_once(text, r"        # -+ coded tools: policy agent\n.*?(?=        # -+ coded tools: orchestrator\n)",
                        "", re.S)
    if "policy_risk_escalation" in text or "evaluate_policy" in text:
        raise SystemExit("the policy agent is still referenced in the lean network; update the build script")
    return text


def source_text() -> str:
    return SOURCE.read_bytes().decode("utf-8")  # bytes: keep line endings exactly as they are


def main() -> None:
    TARGET.write_bytes(build(source_text()).encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
